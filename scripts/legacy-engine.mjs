// Assembles the ES3 engine that scripts/build.mjs puts between the [engine:start] and [engine:end] markers of the classic InDesign
// JSX: the shared word lists and endings from packages/core/src, the generated Unicode tables, and the
// hand-written ES3 port in packages/core/es3. tests/legacy-engine.test.ts loads the same source into a
// sandbox, so what the tests check is what ships.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const es3 = path.join(root, "packages", "core", "es3");

/** The ES3 files, in the order they are joined. */
export const LEGACY_ENGINE_FILES = [
  path.join(es3, "unicode-tables.js"),
  path.join(es3, "web-addresses.js"),
  path.join(es3, "scramble-engine.js"),
];

// One string per first letter, as in top-level-domains.ts, so the injected list stays readable.
function endingsSource(endings) {
  const groups = [];
  for (const ending of endings) {
    const group = groups[groups.length - 1];
    if (group && group[0][0] === ending[0]) group.push(ending);
    else groups.push([ending]);
  }
  return `var TOP_LEVEL_DOMAINS = [\n${groups.map((group) => `  ${JSON.stringify(group.join(" "))}`).join(",\n")}\n].join(" ").split(" ");`;
}

/**
 * The engine block, unindented: plain ES3 declarations that share one scope with the script around them.
 * Takes the lists from packages/core/src/word-lists.ts and top-level-domains.ts.
 */
export async function legacyEngineSource({ commonWords, unwelcomeFragments, topLevelDomains }) {
  for (const [name, words] of [["COMMON_WORDS", commonWords], ["UNWELCOME_FRAGMENTS", unwelcomeFragments], ["TOP_LEVEL_DOMAINS", topLevelDomains]]) {
    if (!words.length || !words.every((word) => /^[a-z]+$/.test(word))) throw new Error(`${name} must be lowercase ASCII words.`);
  }
  const files = await Promise.all(LEGACY_ENGINE_FILES.map((file) => readFile(file, "utf8")));
  const source = [
    "// Generated by scripts/build.mjs from packages/core: the lists in src/word-lists.ts and src/top-level-domains.ts,",
    "// then es3/unicode-tables.js, es3/web-addresses.js and es3/scramble-engine.js. Edit those, not this block.",
    `var COMMON_WORDS = ${JSON.stringify([...commonWords])};`,
    `var UNWELCOME_FRAGMENTS = ${JSON.stringify([...unwelcomeFragments])};`,
    endingsSource(topLevelDomains),
    "",
    ...files.map((file) => file.trimEnd() + "\n"),
  ].join("\n");

  // ExtendScript may read a JSX file without a byte-order mark in the system encoding, so the engine keeps
  // to ASCII and writes every other character as an escape.
  const nonAscii = source.match(/[^\x09\x0a\x0d\x20-\x7e]/);
  if (nonAscii) {
    const line = source.slice(0, nonAscii.index).split("\n").length;
    throw new Error(`The ES3 engine must be ASCII; found U+${nonAscii[0].codePointAt(0).toString(16)} on line ${line} of the engine block.`);
  }
  return source.trimEnd() + "\n";
}
