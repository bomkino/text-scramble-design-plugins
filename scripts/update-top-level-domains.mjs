// Refreshes packages/core/src/top-level-domains.ts from IANA's list of every delegated top-level domain.
// The engine uses it to recognise bare web addresses such as "studio.design". Run it now and then:
// `npm run update-tlds`. A stale list only means a brand-new ending is treated as an ordinary word.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const response = await fetch("https://data.iana.org/TLD/tlds-alpha-by-domain.txt");
if (!response.ok) throw new Error(`IANA returned ${response.status}.`);
const lines = (await response.text()).split("\n");
const version = lines[0].replace(/^#\s*/, "").trim();
const domains = lines
  .slice(1)
  .map((line) => line.trim().toLowerCase())
  .filter((line) => /^[a-z]+$/.test(line))
  .sort();
const groups = new Map();
for (const domain of domains) groups.set(domain[0], [...(groups.get(domain[0]) ?? []), domain]);

const source = `// Generated by scripts/update-top-level-domains.mjs from https://data.iana.org/TLD/tlds-alpha-by-domain.txt
// (${version}). ASCII endings only. Do not edit by hand.
export const TOP_LEVEL_DOMAINS: readonly string[] = [
${[...groups.values()].map((group) => `  ${JSON.stringify(group.join(" "))},`).join("\n")}
]
  .join(" ")
  .split(" ");
`;
await writeFile(path.join(root, "packages", "core", "src", "top-level-domains.ts"), source);
console.log(`Wrote ${domains.length} top-level domains (${version}).`);
